/**
 * Generates docs/FIELD-MAPPING.md from the template itself and from
 * src/pdf/fieldMap.ts, so the documentation can never drift from the code:
 *   npm run report:fields
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PDFDocument } from 'pdf-lib';
import { readTemplateFields } from '../src/pdf/engine';
import { FIELD_MAPPINGS, INTENTIONALLY_EMPTY, MIRROR_TURKISH_ROWS, SIGNATURE_AREA } from '../src/pdf/fieldMap';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const templatePath = resolve(root, 'public/form/antrag-aufenthaltstitel-d-tr.pdf');
const bytes = new Uint8Array(readFileSync(templatePath));
const doc = await PDFDocument.load(bytes, { updateMetadata: false });
const fields = readTemplateFields(doc);

const n = (x: number) => x.toFixed(1);
const esc = (s: string) => s.replace(/\|/g, '\\|');

const rows = FIELD_MAPPINGS.map((m, i) => {
  const f = fields.get(m.pdfField);
  const rect = f ? `${n(f.rect.x)}, ${n(f.rect.y)}, ${n(f.rect.width)} × ${n(f.rect.height)}` : '**missing**';
  const kind = m.kind === 'text' ? `text (${m.style.vAlign === 'underline' ? 'on line' : 'box'}, ${m.style.fontSize}→${m.style.minFontSize} pt${m.style.wrap ? ', 2 lines' : ''})` : 'check box (×)';
  return `| ${i + 1} | \`${m.pdfField}\` | ${m.page} | ${rect} | ${esc(m.formLabel)} | ${kind} | ${m.sourcePaths.map((p) => `\`${p}\``).join(', ')} | ${esc(m.note ?? '')} |`;
});

const unmapped = [...fields.keys()].filter((name) => !FIELD_MAPPINGS.some((m) => m.pdfField === name));

const md = `# PDF field mapping

_Generated by \`npm run report:fields\` from \`src/pdf/fieldMap.ts\` and the template itself. Do not edit by hand._

## Template

| | |
|---|---|
| File | \`public/form/antrag-aufenthaltstitel-d-tr.pdf\` (original file \`amt-m-m31-antrag-ae-tr-data.pdf\`, unmodified) |
| Title | Antrag auf Erteilung/Verlängerung eines Aufenthaltstitels / Bir ikamet ünvanının (oturum izni) verilmesi / uzatılması için dilekçe (D / TR) |
| Form code | E / Z - 008.40/180 - 12.08 (printed in the left margin of page 1) |
| SHA-256 | \`${createHash('sha256').update(bytes).digest('hex')}\` |
| Pages | ${doc.getPageCount()} × ${n(doc.getPage(0).getWidth())} × ${n(doc.getPage(0).getHeight())} pt (A4), no rotation |
| Form technology | AcroForm, ${fields.size} widgets (${[...fields.values()].filter((f) => f.type === 'text').length} text fields, ${[...fields.values()].filter((f) => f.type === 'checkbox').length} check boxes), no XFA, no JavaScript |
| Text layer | none – all printed text is stored as image masks (the PDF is not searchable) |

## How the mapping was established

1. All AcroForm widgets were listed with their names, types and rectangles.
2. Both pages were rendered (150 and 288 dpi) and every widget rectangle was matched to the printed label next to it.
   The generic field names (\`undefined_2\`, \`Text27\`, \`Check Box13\` …) carry no meaning, so this visual match is the source of truth.
3. Rendering with and without annotations showed that the empty widgets draw nothing: all boxes and lines are part of the page content.
   Checked check boxes in the template show a cross (\`/MK /CA "8"\`); the app draws the same cross.
4. Underline-type fields ("Ja, wann ___", "verwitwet seit ___", "dul ___", "Hamburg, den ___") and the signature line were located by pixel analysis;
   text on those fields sits on the printed line instead of being vertically centred.
5. Tests (\`tests/template-mapping.test.ts\`, \`tests/generate.test.ts\`) assert that every template field is mapped exactly once, with the right
   type and page, and that every printed value lies inside its field rectangle.

Positions of all AcroForm-backed values are read from the template at run time (widget \`/Rect\`), never hard-coded.

## Fields (PDF user space, origin bottom-left, pt)

| # | PDF field | Page | x, y, w × h | Printed label | Rendering | Wizard answer(s) | Notes |
|---|---|---|---|---|---|---|---|
${rows.join('\n')}

Unmapped template fields: ${unmapped.length === 0 ? 'none' : unmapped.map((u) => `\`${u}\``).join(', ')}.

## Signature (coordinate-based)

The form has **no field** for the signature. It is placed on page ${SIGNATURE_AREA.page} in the box
x = ${SIGNATURE_AREA.x}, y = ${SIGNATURE_AREA.y}, ${SIGNATURE_AREA.width} × ${SIGNATURE_AREA.height} pt — between the printed signature line
(y ≈ 81.8 pt, x 62–249 pt) and the lowest ink of the "Hamburg," text above it (y ≈ 116.7 pt). The drawn signature is scaled to fit and keeps its
aspect ratio. Label: ${SIGNATURE_AREA.formLabel}.

## Items that intentionally receive no input

${INTENTIONALLY_EMPTY.map((i) => `- ${i}`).join('\n')}
- "Hamburg, den" / "Hamburg," is pre-printed – only the date is filled in.
- There are no fields reserved for the authority on this form.

## Flagged decisions – please review

| Topic | Decision | Where |
|---|---|---|
| Signature position | Coordinate-based (no field exists); measured, visually verified. | \`SIGNATURE_AREA\` |
| Turkish duplicate rows | Marital status and both "Ja/Nein" requests are printed twice (German row, Turkish row). The answer is ticked in **both** rows (\`MIRROR_TURKISH_ROWS = ${MIRROR_TURKISH_ROWS}\`). Set to \`false\` to tick the German row only. | \`fieldMap.ts\` |
| Born in Germany | If ticked, the entry-date field reads "in Deutschland geboren" (wording chosen by the app). | \`undefined_14\` |
| Unknown parent | Prints "unbekannt". | \`undefined_39\`, \`undefined_40\` |
| Choice answers | Eye colour, purpose of stay and means of support are printed with German terms defined by the app (see \`src/form/options.ts\`); they are not taken from the form. | \`options.ts\` |
| Free text | Free-text answers are printed exactly as typed. The app asks for German where sensible but never translates user input. | – |
| Flattening | After filling, all form widgets are removed so every viewer shows the same result and values cannot be edited unnoticed. | \`engine.ts\` |
| Form version | Mapping is valid for this exact file (checksum enforced at run time). A new version of the form must be re-analysed. | \`assets.ts\` |
`;

mkdirSync(resolve(root, 'docs'), { recursive: true });
writeFileSync(resolve(root, 'docs/FIELD-MAPPING.md'), md);
console.log(`Wrote docs/FIELD-MAPPING.md (${FIELD_MAPPINGS.length} mappings, ${unmapped.length} unmapped)`);
